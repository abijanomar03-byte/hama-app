insert into storage.buckets (id, name, public) values ('property-media','property-media',false)
on conflict (id) do update set public = false;

-- Public read is intentionally disabled. Hama should generate signed URLs from the server.
drop policy if exists media_storage_read on storage.objects;
create policy media_storage_read on storage.objects for select using (
  bucket_id = 'property-media' and (
    auth.uid()::text = (storage.foldername(name))[1]
    or exists (
      select 1 from public.properties p
      where p.owner_id = auth.uid() and p.id::text = (storage.foldername(name))[2]
    )
  )
);

drop policy if exists media_storage_insert on storage.objects;
create policy media_storage_insert on storage.objects for insert with check (
  bucket_id = 'property-media' and auth.uid()::text = (storage.foldername(name))[1]
);
drop policy if exists media_storage_update on storage.objects;
create policy media_storage_update on storage.objects for update using (
  bucket_id = 'property-media' and auth.uid()::text = (storage.foldername(name))[1]
) with check (
  bucket_id = 'property-media' and auth.uid()::text = (storage.foldername(name))[1]
);
drop policy if exists media_storage_delete on storage.objects;
create policy media_storage_delete on storage.objects for delete using (
  bucket_id = 'property-media' and auth.uid()::text = (storage.foldername(name))[1]
);

