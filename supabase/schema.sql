-- =========================
-- COMMON FUNCTIONS
-- =========================
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists trg_profiles_updated_at on public.profiles;
create trigger trg_profiles_updated_at before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists trg_properties_updated_at on public.properties;
create trigger trg_properties_updated_at before update on public.properties
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, full_name, phone)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', ''), coalesce(new.phone, new.raw_user_meta_data->>'phone'))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists trg_auth_user_profile on auth.users;
create trigger trg_auth_user_profile after insert on auth.users
for each row execute function public.handle_new_user();

-- Enforce that published listings have the required media and a valid vacancy date.
create or replace function public.validate_property_publish()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  media_count integer;
begin
  if new.status = 'active' then
    if new.published_at is null then new.published_at = now(); end if;
    if new.vacancy_date < current_date then
      raise exception 'Vacancy date cannot be in the past';
    end if;
    select count(*) into media_count
    from public.property_media
    where property_id = new.id and media_type = 'photo' and ai_verified = true and freshness_verified = true;
    if media_count < 4 then
      raise exception 'A listing needs 4 verified room photos before it can be published';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists trg_validate_property_publish on public.properties;
create constraint trigger trg_validate_property_publish
after insert or update of status, vacancy_date on public.properties
initially deferred for each row execute function public.validate_property_publish();

-- Expire listings automatically when they are far past vacancy or explicitly expired.
create or replace function public.expire_old_listings()
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.properties
  set status = 'expired', updated_at = now()
  where status = 'active' and vacancy_date < current_date - 30;
end $$;

-- Unlock browsing only after a user has a published property.
create or replace function public.unlock_hunting_access(p_property_id uuid)
returns public.hunting_access language plpgsql security definer set search_path = public as $$
declare
  p public.properties;
  result public.hunting_access;
begin
  select * into p from public.properties where id = p_property_id and owner_id = auth.uid() and status = 'active';
  if p.id is null then raise exception 'You can only unlock access with your own active listing'; end if;
  insert into public.hunting_access(user_id, unlocked_by_property_id)
  values(auth.uid(), p_property_id)
  on conflict (user_id) do update set unlocked_by_property_id = excluded.unlocked_by_property_id;
  select * into result from public.hunting_access where user_id = auth.uid();
  return result;
end $$;

