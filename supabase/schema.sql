-- Profiles are private; expose only a deliberately-safe public projection.
drop policy if exists profiles_public_read on public.profiles;
drop policy if exists profiles_self_read on public.profiles;
create policy profiles_self_read on public.profiles for select using (auth.uid() = id);
drop view if exists public.public_profiles;
create view public.public_profiles as
select id, full_name, avatar_path, is_verified, created_at
from public.profiles;

drop policy if exists profiles_self_update on public.profiles;
create policy profiles_self_update on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists profiles_self_insert on public.profiles;
create policy profiles_self_insert on public.profiles for insert with check (auth.uid() = id);

-- Locations are public reference data
 drop policy if exists locations_public_read on public.locations;
create policy locations_public_read on public.locations for select using (is_active = true);

-- Listings: everyone may read active listings, owners can manage own rows.
drop policy if exists properties_public_active_read on public.properties;
create policy properties_public_active_read on public.properties for select using (status = 'active' or owner_id = auth.uid());
drop policy if exists properties_owner_insert on public.properties;
create policy properties_owner_insert on public.properties for insert with check (auth.uid() = owner_id);
drop policy if exists properties_owner_update on public.properties;
create policy properties_owner_update on public.properties for update using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
drop policy if exists properties_owner_delete on public.properties;
create policy properties_owner_delete on public.properties for delete using (auth.uid() = owner_id);

-- Media: public read for active listings, owner can manage media for own property.
drop policy if exists media_public_read on public.property_media;
create policy media_public_read on public.property_media for select using (
  exists (select 1 from public.properties p where p.id = property_id and (p.status = 'active' or p.owner_id = auth.uid()))
);
drop policy if exists media_owner_insert on public.property_media;
create policy media_owner_insert on public.property_media for insert with check (
  exists (select 1 from public.properties p where p.id = property_id and p.owner_id = auth.uid())
);
drop policy if exists media_owner_update on public.property_media;
create policy media_owner_update on public.property_media for update using (
  exists (select 1 from public.properties p where p.id = property_id and p.owner_id = auth.uid())
) with check (
  exists (select 1 from public.properties p where p.id = property_id and p.owner_id = auth.uid())
);
drop policy if exists media_owner_delete on public.property_media;
create policy media_owner_delete on public.property_media for delete using (
  exists (select 1 from public.properties p where p.id = property_id and p.owner_id = auth.uid())
);

-- Access record is private to the owner.
drop policy if exists hunting_self_read on public.hunting_access;
create policy hunting_self_read on public.hunting_access for select using (auth.uid() = user_id);

-- Favorites
 drop policy if exists favorites_self_read on public.favorites;
create policy favorites_self_read on public.favorites for select using (auth.uid() = user_id);
drop policy if exists favorites_self_insert on public.favorites;
create policy favorites_self_insert on public.favorites for insert with check (auth.uid() = user_id);
drop policy if exists favorites_self_delete on public.favorites;
create policy favorites_self_delete on public.favorites for delete using (auth.uid() = user_id);

-- Conversations: participants only.
drop policy if exists conversations_participant_read on public.conversations;
create policy conversations_participant_read on public.conversations for select using (auth.uid() = created_by or auth.uid() = other_user_id);
drop policy if exists conversations_participant_insert on public.conversations;
create policy conversations_participant_insert on public.conversations for insert with check (auth.uid() = created_by);

-- Messages: participants only and sender must equal logged-in user.
drop policy if exists messages_participant_read on public.messages;
create policy messages_participant_read on public.messages for select using (
  exists (select 1 from public.conversations c where c.id = conversation_id and (c.created_by = auth.uid() or c.other_user_id = auth.uid()))
);
drop policy if exists messages_participant_insert on public.messages;
create policy messages_participant_insert on public.messages for insert with check (
  auth.uid() = sender_id and exists (select 1 from public.conversations c where c.id = conversation_id and (c.created_by = auth.uid() or c.other_user_id = auth.uid()))
);
drop policy if exists messages_receiver_update on public.messages;
create policy messages_receiver_update on public.messages for update using (
  exists (select 1 from public.conversations c where c.id = conversation_id and (c.created_by = auth.uid() or c.other_user_id = auth.uid()))
) with check (
  exists (select 1 from public.conversations c where c.id = conversation_id and (c.created_by = auth.uid() or c.other_user_id = auth.uid()))
);

-- Notifications are private.
drop policy if exists notifications_self_read on public.notifications;
create policy notifications_self_read on public.notifications for select using (auth.uid() = user_id);
drop policy if exists notifications_self_update on public.notifications;
create policy notifications_self_update on public.notifications for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Reports may be created by signed-in users. Only admins can read/manage.
drop policy if exists reports_user_insert on public.reports;
create policy reports_user_insert on public.reports for insert with check (auth.uid() = reporter_id);
drop policy if exists reports_admin_all on public.reports;
create policy reports_admin_all on public.reports for all using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true)) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true));

-- Audit log is server/admin only via service role; authenticated users cannot read.
drop policy if exists audit_admin_read on public.audit_log;
create policy audit_admin_read on public.audit_log for select using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true));

