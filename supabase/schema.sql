-- =========================
-- ENUMS
-- =========================
do $$ begin
  create type public.property_status as enum ('draft','active','reserved','rented','suspended','expired');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.media_type as enum ('photo','video');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.room_type as enum ('sitting_room','bedroom','kitchen','washroom','exterior');
exception when duplicate_object then null; end $$;

-- =========================
-- PROFILES
-- =========================
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  avatar_path text,
  is_verified boolean not null default false,
  is_admin boolean not null default false,
  notice_confirmed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================
-- LOCATION REFERENCE DATA
-- =========================
create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  hood text not null,
  area text not null,
  slug text generated always as (lower(regexp_replace(trim(hood || '-' || area), '[^a-zA-Z0-9]+', '-', 'g'))) stored,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (hood, area),
  unique (slug)
);

-- =========================
-- PROPERTIES / LISTINGS
-- =========================
create table if not exists public.properties (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete restrict,
  location_id bigint references public.locations(id) on delete restrict,
  hood text not null,
  area text not null,
  house_type text not null check (house_type in ('Bedsitter','1 Bedroom','2 Bedrooms','3 Bedrooms')),
  rent integer not null check (rent > 0 and rent <= 100000000),
  deposit integer check (deposit is null or deposit >= 0),
  vacancy_date date not null,
  water text,
  security text,
  road text,
  internet text,
  parking text,
  pets_allowed boolean,
  description text check (description is null or length(description) <= 3000),
  status public.property_status not null default 'draft',
  published_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint properties_area_consistency foreign key (location_id) references public.locations(id) on delete restrict
);

-- =========================
-- PROPERTY MEDIA
-- =========================
create table if not exists public.property_media (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties(id) on delete cascade,
  room_type public.room_type,
  media_type public.media_type not null,
  storage_path text not null unique,
  captured_at timestamptz,
  latitude numeric(9,6),
  longitude numeric(9,6),
  ai_verified boolean not null default false,
  freshness_verified boolean not null default false,
  width integer,
  height integer,
  duration_seconds integer,
  file_size_bytes bigint,
  checksum text,
  created_at timestamptz not null default now(),
  constraint media_video_duration check (duration_seconds is null or (duration_seconds >= 1 and duration_seconds <= 30))
);

-- =========================
-- USER ACCESS / POST-TO-UNLOCK
-- =========================
create table if not exists public.hunting_access (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  unlocked_at timestamptz not null default now(),
  unlocked_by_property_id uuid references public.properties(id) on delete set null
);

-- =========================
-- FAVORITES
-- =========================
create table if not exists public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  property_id uuid not null references public.properties(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, property_id)
);

-- =========================
-- CONVERSATIONS / MESSAGES
-- =========================
create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  property_id uuid references public.properties(id) on delete set null,
  created_by uuid not null references public.profiles(id) on delete restrict,
  other_user_id uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  unique(property_id, created_by, other_user_id),
  constraint conversation_different_users check (created_by <> other_user_id)
);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete restrict,
  body text not null check (length(trim(body)) between 1 and 4000),
  created_at timestamptz not null default now(),
  read_at timestamptz
);

-- =========================
-- NOTIFICATIONS
-- =========================
create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null,
  title text not null,
  body text,
  payload jsonb not null default '{}'::jsonb,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

-- =========================
-- REPORTS / AUDIT
-- =========================
create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties(id) on delete cascade,
  reporter_id uuid references public.profiles(id) on delete set null,
  reason text not null,
  details text,
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

